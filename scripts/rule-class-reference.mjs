// Generates the "Rule classes" reference in README.md from the published rule-set JSON Schema, so the
// README can only describe what the schema checks (cognovis/fhir-billing-core#16).
//
//   bun scripts/rule-class-reference.mjs           rewrites the block in README.md
//   bun scripts/rule-class-reference.mjs --check   exits 1 when the block is not current
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export const SCHEMA_FILE = 'packages/rules/schema/billing-rule-set.schema.json'
export const README_FILE = 'README.md'
const START = '<!-- rule-class-reference:start generated by scripts/rule-class-reference.mjs from packages/rules/schema/billing-rule-set.schema.json; edit the schema, not this block -->'
const END = '<!-- rule-class-reference:end -->'
const SHARED = ['countingScope', 'exceptWhen', 'modifierExceptions']

function resolve(schema, node) {
  if (typeof node?.$ref !== 'string' || !node.$ref.startsWith('#/')) return node
  const target = node.$ref.slice(2).split('/').reduce((value, key) => value?.[key], schema)
  if (target === undefined) throw new Error(`Unresolvable reference ${node.$ref}`)
  return { ...resolve(schema, target), ...Object.fromEntries(Object.entries(node).filter(([key]) => key !== '$ref')) }
}

function cell(text) {
  return String(text).replaceAll('|', '\\|').replaceAll('\n', ' ')
}

/** Selectors are described once by their own row; every other object parameter lists its members, one level deep. */
const OPAQUE = new Set(['#/$defs/selector', '#/$defs/codeSelector', '#/$defs/alternationMap'])

function rows(schema, name, property, required) {
  const resolved = resolve(schema, property)
  const row = `| \`${name}\` | ${required ? 'yes' : 'no'} | ${cell(resolved.description ?? '')} |`
  if (OPAQUE.has(property.$ref)) return [row]
  const items = resolved.type === 'array' ? resolve(schema, resolved.items ?? {}) : undefined
  const members = (items ?? resolved).properties
  if (members === undefined) return [row]
  const memberRequired = new Set((items ?? resolved).required ?? [])
  const prefix = items === undefined ? `${name}.` : `${name}[].`
  return [row, ...Object.entries(members).filter(([, member]) => member !== true).map(([child, member]) => {
    const described = resolve(schema, member)
    if (described.description === undefined) throw new Error(`${prefix}${child} needs a description in the schema.`)
    return `| \`${prefix}${child}\` | ${memberRequired.has(child) ? 'yes' : 'no'} | ${cell(described.description)} |`
  })]
}

function sentence(text) {
  return text.charAt(0).toUpperCase() + text.slice(1)
}

/** Indented JSON with each array of scalars on one line. */
function compactJson(value) {
  return JSON.stringify(value, null, 2).replace(/\[\n\s+([^[\]{}]*?)\n\s*\]/g, (_match, inner) => `[${inner.split(/,\n\s*/).join(', ')}]`)
}

/** The Markdown block between the markers, without them. */
export function renderRuleClassReference(schema) {
  const classes = schema.$defs.ruleClassParameters
  const lines = [
    'Each generic rule class reads the parameters below; the JSON Schema checks them per `class`. A',
    'class Billing Core does not know takes any `parameters` object. Every class except',
    '`contract-code-list` also accepts the shared optional parameters:',
    '',
    '| Parameter | Meaning |',
    '| --- | --- |',
    ...SHARED.map((name) => `| \`${name}\` | ${cell(sentence(resolve(schema, schema.$defs[name]).description.replace(/^Optional: /, '')))} |`),
    '',
    'A class marked *closed* refuses a parameter it does not list; an *open* class keeps it.',
  ]
  for (const [ruleClass, definition] of Object.entries(classes)) {
    const required = new Set(definition.required ?? [])
    const own = Object.entries(definition.properties).filter(([name]) => !SHARED.includes(name))
    const example = { id: `example-${ruleClass}`, class: ruleClass, mustUnderstand: true, effect: 'reject', priority: 10, parameters: definition.examples[0] }
    lines.push(
      '',
      `### \`${ruleClass}\``,
      '',
      definition.description,
      '',
      `*${definition.additionalProperties === false ? 'Closed' : 'Open'}; takes ${SHARED.every((name) => name in definition.properties) ? 'the' : 'no'} shared parameters.*`,
      '',
      '| Parameter | Required | Meaning |',
      '| --- | --- | --- |',
      ...own.flatMap(([name, property]) => rows(schema, name, property, required.has(name))),
      '',
      '```json',
      compactJson(example),
      '```',
    )
  }
  return lines.join('\n')
}

/** The README with its block replaced by the rendered reference. */
export function withRuleClassReference(readme, rendered) {
  const start = readme.indexOf(START)
  const end = readme.indexOf(END)
  if (start === -1 || end === -1 || end < start) throw new Error(`${README_FILE} must contain the rule-class-reference markers once.`)
  return `${readme.slice(0, start + START.length)}\n${rendered}\n${readme.slice(end)}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const schema = JSON.parse(readFileSync(SCHEMA_FILE, 'utf8'))
  const readme = readFileSync(README_FILE, 'utf8')
  const current = withRuleClassReference(readme, renderRuleClassReference(schema))
  if (process.argv.includes('--check')) {
    if (current !== readme) {
      console.error(`${README_FILE} rule classes are not current; run bun scripts/rule-class-reference.mjs`)
      process.exit(1)
    }
  } else if (current !== readme) {
    writeFileSync(README_FILE, current)
  }
}
